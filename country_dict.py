def _norm(s):
    s = str(s).replace("’", "'")  # WHR's "Côte d’Ivoire"
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    s = s.lower().replace("&", " and ")
    s = re.sub(r"[^a-z0-9 ]+", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return re.sub(r"^the ", "", s)


# Names: countries only, plus explicit aliases. Aggregates match by code or AGGREGATE_NAME_ALIASES, never by name.
_NAME_LOOKUP = {_norm(v): k for k, v in COUNTRIES.items() if k not in AGGREGATES}
_NAME_LOOKUP.update({_norm(k): v for k, v in NAME_ALIASES.items()})
_NAME_LOOKUP.update({_norm(k): v for k, v in AGGREGATE_NAME_ALIASES.items()})


def to_iso3(code=None, name=None):
    """Return the unified code (country ISO3 or World Bank aggregate), or None for anything else."""
    if code is not None and not pd.isna(code) and str(code).strip():
        c = str(code).strip().upper()
        c = CODE_ALIASES.get(c, c)
        if c in COUNTRIES:
            return c
    if name is not None and not pd.isna(name):
        hit = _NAME_LOOKUP.get(_norm(name))
        if hit is None and "(" in str(name):  # e.g. "Cambodia (Kampuchea)": retry without the bracket
            hit = _NAME_LOOKUP.get(_norm(re.sub(r"\s*\(.*?\)", "", str(name))))
            if hit in AGGREGATES:  # e.g. a "World (excl. ...)" subtotal is not the World
                hit = None
        return hit
    return None


def unify_countries(df: pd.DataFrame, code_col: str | None = None, name_col: str | None = None,
                    label: str = "") -> pd.DataFrame:
    """Add unified country_code / country_name, drop rows that are neither a country nor a World
    Bank aggregate (logged). Looks up each distinct (code, name) pair once, not every row."""
    codes = df[code_col] if code_col else pd.Series(None, index=df.index, dtype=object)
    names = df[name_col] if name_col else pd.Series(None, index=df.index, dtype=object)
    pairs = pd.MultiIndex.from_arrays([codes.astype(object), names.astype(object)])
    lookup = {pair: to_iso3(*pair) for pair in pairs.unique()}
    out = df.assign(country_code=[lookup[pair] for pair in pairs])
    dropped = out[out["country_code"].isna()]
    if len(dropped):
        what = sorted(set(map(str, dropped[name_col] if name_col else dropped[code_col])))
        log.info("%s: dropped %d rows (not a country or a World Bank aggregate): %s", label, len(dropped), what[:20])
    out = out.dropna(subset=["country_code"]).copy()
    out["country_name"] = out["country_code"].map(COUNTRIES)
    return out
